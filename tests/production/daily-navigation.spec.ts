import {test,expect,type Page} from '@playwright/test'
async function database(page:Page){return page.evaluate(()=>JSON.parse(localStorage.getItem('wordpal.database.v2')!))}
test('正式网页子路径：取消后可保存离开，返回和刷新继续原检查点，宠物屋不开放额外练习',async({page})=>{
 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message))
 await page.goto('./#/pages/home/index',{waitUntil:'networkidle'})
 await page.locator('.hero-cta').click()
 await expect(page.locator('.daily-session-lock')).toBeVisible()
 await expect(page.locator('.study-round-tools')).toBeDisabled()
 await page.locator('.rating-grid').getByRole('button').nth(2).click()
 const before=await database(page),plan=before.courseProgress.starter.dailyPlan
 await page.locator('.bottom-nav').getByRole('button',{name:'首页',exact:true}).click()
 await page.locator('.uni-modal').getByText('继续学习',{exact:true}).click()
 await expect(page.locator('.uni-modal')).toBeHidden()
 await expect(page.locator('.answer-feedback')).toBeVisible()
 await page.locator('.bottom-nav').getByRole('button',{name:'宠物屋',exact:true}).click()
 await expect(page.locator('.uni-modal')).toContainText('本轮进度会保存')
 await page.locator('.uni-modal').getByText('保存并离开',{exact:true}).click()
 await expect(page.locator('.wp-brand-header .brand-subtitle')).toHaveText('PetHouse')
 await page.locator('.lh-learning-toggle').click()
 await expect(page.getByRole('button',{name:'试一试拼写或听写',exact:true})).toHaveCount(0)
 await page.getByRole('button',{name:'一起去学习',exact:true}).click()
 await expect(page.locator('.answer-feedback')).toBeVisible()
 await page.reload({waitUntil:'networkidle'})
 await expect(page.locator('.daily-session-lock')).toBeVisible()
 await expect(page.locator('.answer-feedback')).toBeVisible()
 const after=await database(page)
 expect(after.courseProgress.starter.dailyPlan).toEqual(plan)
 for(const field of ['cards','history','gems','pets','rewardIds'])expect(after[field]).toEqual(before[field])
 expect(errors).toEqual([])
})
